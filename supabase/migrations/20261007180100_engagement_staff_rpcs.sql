CREATE OR REPLACE FUNCTION public.engagement_threads()
RETURNS json
LANGUAGE plpgsql STABLE SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_company uuid := public._engagement_require_hr();
BEGIN
  RETURN (
    WITH agg AS (
      SELECT m.employee_id,
             count(*) FILTER (WHERE m.sender_kind = 'employee' AND m.read_at IS NULL)::int AS unread
      FROM public.messages m
      WHERE m.company_id = v_company
      GROUP BY m.employee_id
    ),
    latest AS (
      SELECT DISTINCT ON (m.employee_id) m.employee_id, m.content, m.sender_kind, m.created_at
      FROM public.messages m
      WHERE m.company_id = v_company
      ORDER BY m.employee_id, m.created_at DESC, m.id DESC
    )
    SELECT COALESCE(json_agg(json_build_object(
      'employee_id', e.id, 'name', e.name, 'rank', e.rank, 'avatar_url', e.avatar_url, 'status', e.status,
      'department', d.name,
      'last_content', left(l.content, 160), 'last_from_staff', l.sender_kind = 'staff', 'last_at', l.created_at,
      'unread', a.unread
    ) ORDER BY l.created_at DESC), '[]'::json)
    FROM agg a
    JOIN latest l ON l.employee_id = a.employee_id
    JOIN public.employees e ON e.id = a.employee_id AND e.company_id = v_company
    LEFT JOIN public.departments d ON d.id = e.department_id
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.engagement_thread(p_employee uuid, p_limit integer DEFAULT 300)
RETURNS json
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_company uuid := public._engagement_require_hr();
  v_emp public.employees;
  v_limit integer := LEAST(GREATEST(COALESCE(p_limit, 300), 1), 1000);
BEGIN
  SELECT * INTO v_emp FROM public.employees e WHERE e.id = p_employee AND e.company_id = v_company;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'That employee is not in your company.' USING ERRCODE = 'P0002';
  END IF;

  -- Opening the thread reads what the employee sent.
  UPDATE public.messages m SET read_at = now()
  WHERE m.employee_id = v_emp.id AND m.company_id = v_company AND m.sender_kind = 'employee' AND m.read_at IS NULL;

  RETURN json_build_object(
    'employee', json_build_object(
      'id', v_emp.id, 'name', v_emp.name, 'rank', v_emp.rank, 'avatar_url', v_emp.avatar_url, 'status', v_emp.status,
      'department', (SELECT d.name FROM public.departments d WHERE d.id = v_emp.department_id)
    ),
    'messages', (
      SELECT COALESCE(json_agg(json_build_object(
        'id', x.id, 'content', x.content, 'sender_kind', x.sender_kind,
        'sender_name', CASE WHEN x.sender_kind = 'staff' THEN public._engagement_staff_name(x.sender_user_id) ELSE v_emp.name END,
        'mine', x.sender_user_id = auth.uid(),
        'created_at', x.created_at, 'read_at', x.read_at
      ) ORDER BY x.created_at, x.id), '[]'::json)
      FROM (
        SELECT m.* FROM public.messages m
        WHERE m.employee_id = v_emp.id AND m.company_id = v_company
        ORDER BY m.created_at DESC, m.id DESC
        LIMIT v_limit
      ) x
    )
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.engagement_send_message(p_employee uuid, p_content text)
RETURNS json
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_company uuid := public._engagement_require_hr();
  v_content text := btrim(COALESCE(p_content, ''));
  v_emp public.employees;
  v_row public.messages;
  v_name text := public._engagement_staff_name(auth.uid());
BEGIN
  IF v_content = '' THEN
    RAISE EXCEPTION 'Write a message first.' USING ERRCODE = '22023';
  END IF;
  IF char_length(v_content) > 2000 THEN
    RAISE EXCEPTION 'A message can be at most 2000 characters.' USING ERRCODE = '22023';
  END IF;
  SELECT * INTO v_emp FROM public.employees e WHERE e.id = p_employee AND e.company_id = v_company;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'That employee is not in your company.' USING ERRCODE = 'P0002';
  END IF;
  IF v_emp.status <> 'active' THEN
    RAISE EXCEPTION '% is no longer active, so they cannot read new messages.', v_emp.name USING ERRCODE = '22023';
  END IF;
  IF (SELECT count(*) FROM public.messages m
      WHERE m.sender_user_id = auth.uid() AND m.created_at > now() - interval '1 minute') >= 30 THEN
    RAISE EXCEPTION 'You are sending messages too quickly. Wait a moment.' USING ERRCODE = '54000';
  END IF;

  INSERT INTO public.messages (company_id, employee_id, sender_kind, sender_user_id, content)
  VALUES (v_company, v_emp.id, 'staff', auth.uid(), v_content)
  RETURNING * INTO v_row;

  -- HR has answered, so everything the employee sent is read.
  UPDATE public.messages m SET read_at = now()
  WHERE m.employee_id = v_emp.id AND m.sender_kind = 'employee' AND m.read_at IS NULL;

  PERFORM public.notify_employee(v_company, v_emp.id, 'message', format('New message from HR (%s)', v_name), left(v_content, 140), '/portal/messages');
  PERFORM public._engagement_ping_thread(v_emp.id, v_row.id);

  RETURN json_build_object(
    'id', v_row.id, 'content', v_row.content, 'sender_kind', v_row.sender_kind, 'sender_name', v_name,
    'mine', true, 'created_at', v_row.created_at, 'read_at', v_row.read_at
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.engagement_mark_thread_read(p_employee uuid)
RETURNS integer
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_company uuid := public._engagement_require_hr();
  v_count integer;
BEGIN
  UPDATE public.messages m SET read_at = now()
  WHERE m.employee_id = p_employee AND m.company_id = v_company AND m.sender_kind = 'employee' AND m.read_at IS NULL;
  GET DIAGNOSTICS v_count = ROW_COUNT;
  RETURN v_count;
END;
$$;

