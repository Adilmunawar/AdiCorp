CREATE OR REPLACE FUNCTION public.engagement_complaints()
RETURNS json
LANGUAGE plpgsql STABLE SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_company uuid := public._engagement_require_hr();
BEGIN
  RETURN (
    SELECT COALESCE(json_agg(json_build_object(
      'id', c.id, 'subject', c.subject, 'description', c.description, 'status', c.status,
      'is_anonymous', c.is_anonymous,
      'employee_id', CASE WHEN c.is_anonymous THEN NULL ELSE c.employee_id END,
      'employee_name', CASE WHEN c.is_anonymous THEN NULL ELSE e.name END,
      'employee_rank', CASE WHEN c.is_anonymous THEN NULL ELSE e.rank END,
      'employee_avatar', CASE WHEN c.is_anonymous THEN NULL ELSE e.avatar_url END,
      'response', c.response,
      'responder_name', CASE WHEN c.responded_by IS NOT NULL THEN public._engagement_staff_name(c.responded_by) END,
      'responded_at', c.responded_at, 'created_at', c.created_at, 'updated_at', c.updated_at
    ) ORDER BY CASE c.status WHEN 'pending' THEN 0 WHEN 'investigating' THEN 1 ELSE 2 END, c.created_at DESC, c.id DESC), '[]'::json)
    FROM public.complaints c
    LEFT JOIN public.employees e ON e.id = c.employee_id
    WHERE c.company_id = v_company
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.engagement_respond_complaint(p_id uuid, p_status text, p_response text)
RETURNS void
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_company uuid := public._engagement_require_hr();
  v_old public.complaints;
  v_response text := NULLIF(btrim(COALESCE(p_response, '')), '');
  v_status_changed boolean;
  v_response_changed boolean;
  v_title text;
BEGIN
  IF p_status NOT IN ('pending', 'investigating', 'resolved') THEN
    RAISE EXCEPTION 'Choose a status.' USING ERRCODE = '22023';
  END IF;
  IF char_length(COALESCE(v_response, '')) > 2000 THEN
    RAISE EXCEPTION 'The response can be at most 2000 characters.' USING ERRCODE = '22023';
  END IF;

  SELECT * INTO v_old FROM public.complaints c WHERE c.id = p_id AND c.company_id = v_company FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'That complaint no longer exists.' USING ERRCODE = 'P0002';
  END IF;

  v_status_changed := v_old.status IS DISTINCT FROM p_status;
  v_response_changed := v_old.response IS DISTINCT FROM v_response;
  IF NOT v_status_changed AND NOT v_response_changed THEN
    RETURN;
  END IF;

  UPDATE public.complaints c
  SET status = p_status,
      response = v_response,
      responded_by = CASE WHEN v_response_changed THEN auth.uid() ELSE c.responded_by END,
      responded_at = CASE WHEN v_response_changed THEN now() ELSE c.responded_at END
  WHERE c.id = p_id;

  IF NOT v_old.is_anonymous AND v_old.employee_id IS NOT NULL THEN
    v_title := CASE
      WHEN v_status_changed AND p_status = 'resolved' THEN 'Your complaint was resolved'
      WHEN v_response_changed AND v_response IS NOT NULL THEN 'HR responded to your complaint'
      ELSE 'Your complaint is now ' || p_status
    END;
    PERFORM public.notify_employee(v_company, v_old.employee_id, 'complaint', v_title, v_old.subject, '/portal/complaints');
  END IF;

  IF v_status_changed THEN
    PERFORM public.log_activity(
      'complaint.status', format('Marked the complaint "%s" %s', v_old.subject, p_status),
      jsonb_build_object('complaint_id', p_id, 'from', v_old.status, 'to', p_status, 'anonymous', v_old.is_anonymous),
      CASE WHEN v_old.is_anonymous THEN NULL ELSE v_old.employee_id END
    );
  END IF;
  IF v_response_changed THEN
    PERFORM public.log_activity(
      'complaint.response', format('Responded to the complaint "%s"', v_old.subject),
      jsonb_build_object('complaint_id', p_id, 'anonymous', v_old.is_anonymous),
      CASE WHEN v_old.is_anonymous THEN NULL ELSE v_old.employee_id END
    );
  END IF;
END;
$$;

