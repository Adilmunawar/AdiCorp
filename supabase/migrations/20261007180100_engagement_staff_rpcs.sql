-- Engagement 2/4: private config, shared helpers and the staff (owner / HR) RPCs for
-- announcements, polls, complaints, messages and celebrations.
-- Every function is SECURITY DEFINER with an empty search_path, checks the caller's
-- role and company itself, and is granted only to the roles that need it.

-- ---------------------------------------------------------------------------
-- Private schema: server-side secrets (never exposed through the API)
-- ---------------------------------------------------------------------------
CREATE SCHEMA IF NOT EXISTS engagement_private;
REVOKE ALL ON SCHEMA engagement_private FROM PUBLIC, anon, authenticated;

CREATE TABLE IF NOT EXISTS engagement_private.config (
  id boolean PRIMARY KEY DEFAULT true CONSTRAINT config_singleton_chk CHECK (id),
  function_url text,                -- push-send Edge Function
  webhook_secret text NOT NULL,     -- sent by the database to push-send
  chat_secret text NOT NULL,        -- derives the per-employee realtime topic
  vapid_public text,                -- generated by push-send on first use
  vapid_private jsonb,
  vapid_subject text NOT NULL DEFAULT 'https://umybjmuzbxfxdtbumgma.supabase.co',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE engagement_private.config ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON engagement_private.config FROM PUBLIC, anon, authenticated;

