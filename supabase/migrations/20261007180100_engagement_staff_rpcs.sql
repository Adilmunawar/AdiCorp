-- A poll is open while active and not past its closing time.
CREATE OR REPLACE FUNCTION public._engagement_poll_json(p_poll public.polls, p_with_counts boolean)
RETURNS json
LANGUAGE sql STABLE SECURITY DEFINER
SET search_path = ''
AS $$
  WITH opts AS (
    SELECT o.id, o.option_text, o.position,
           (SELECT count(*) FROM public.poll_votes v WHERE v.option_id = o.id AND v.poll_id = o.poll_id)::int AS votes
    FROM public.poll_options o
    WHERE o.poll_id = p_poll.id
  ),
  total AS (SELECT COALESCE(sum(votes), 0)::int AS n FROM opts)
  SELECT json_build_object(
    'id', p_poll.id,
    'question', p_poll.question,
    'description', p_poll.description,
    'status', CASE WHEN p_poll.status = 'active' AND (p_poll.expires_at IS NULL OR p_poll.expires_at > now()) THEN 'open' ELSE 'closed' END,
    'expires_at', p_poll.expires_at,
    'closed_at', COALESCE(p_poll.closed_at, CASE WHEN p_poll.expires_at <= now() THEN p_poll.expires_at END),
    'created_at', p_poll.created_at,
    'author_name', public._engagement_staff_name(p_poll.created_by),
    'total_votes', CASE WHEN p_with_counts THEN (SELECT n FROM total) END,
    'eligible', CASE WHEN p_with_counts THEN (
      SELECT count(*)::int FROM public.employees e WHERE e.company_id = p_poll.company_id AND e.status = 'active'
    ) END,
    'options', (
      SELECT COALESCE(json_agg(json_build_object(
        'id', o.id, 'text', o.option_text, 'position', o.position,
        'votes', CASE WHEN p_with_counts THEN o.votes END,
        'percent', CASE WHEN (SELECT n FROM total) > 0 THEN round(o.votes * 100.0 / (SELECT n FROM total))::int ELSE 0 END
      ) ORDER BY o.position, o.id), '[]'::json)
      FROM opts o
    )
  )
$$;
REVOKE ALL ON FUNCTION public._engagement_poll_json(public.polls, boolean) FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.engagement_polls()
RETURNS json
LANGUAGE plpgsql STABLE SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_company uuid := public._engagement_require_hr();
BEGIN
  RETURN (
    SELECT COALESCE(json_agg(public._engagement_poll_json(p, true)
      ORDER BY (p.status = 'active' AND (p.expires_at IS NULL OR p.expires_at > now())) DESC, p.created_at DESC, p.id DESC), '[]'::json)
    FROM public.polls p
    WHERE p.company_id = v_company
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.engagement_poll_detail(p_id uuid)
RETURNS json
LANGUAGE plpgsql STABLE SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_company uuid := public._engagement_require_hr();
  v_poll public.polls;
BEGIN
  SELECT * INTO v_poll FROM public.polls p WHERE p.id = p_id AND p.company_id = v_company;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'That poll no longer exists.' USING ERRCODE = 'P0002';
  END IF;
  RETURN json_build_object(
    'poll', public._engagement_poll_json(v_poll, true),
    'voters', (
      SELECT COALESCE(json_agg(json_build_object(
        'employee_id', e.id, 'name', e.name, 'rank', e.rank, 'avatar_url', e.avatar_url,
        'option_id', o.id, 'option_text', o.option_text, 'voted_at', v.created_at
      ) ORDER BY o.position, o.id, v.created_at), '[]'::json)
      FROM public.poll_votes v
      JOIN public.employees e ON e.id = v.employee_id
      JOIN public.poll_options o ON o.id = v.option_id
      WHERE v.poll_id = v_poll.id
    ),
    'not_voted', (
      SELECT COALESCE(json_agg(json_build_object('employee_id', e.id, 'name', e.name, 'rank', e.rank, 'avatar_url', e.avatar_url) ORDER BY e.name), '[]'::json)
      FROM public.employees e
      WHERE e.company_id = v_company AND e.status = 'active'
        AND NOT EXISTS (SELECT 1 FROM public.poll_votes v WHERE v.poll_id = v_poll.id AND v.employee_id = e.id)
    )
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.engagement_create_poll(
  p_question text, p_description text, p_options text[], p_expires_at timestamptz DEFAULT NULL
)
RETURNS uuid
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_company uuid := public._engagement_require_hr();
  v_question text := btrim(COALESCE(p_question, ''));
  v_description text := NULLIF(btrim(COALESCE(p_description, '')), '');
  v_options text[];
  v_id uuid;
  v_told integer;
BEGIN
  IF char_length(v_question) < 5 OR char_length(v_question) > 200 THEN
    RAISE EXCEPTION 'The question must be 5 to 200 characters.' USING ERRCODE = '22023';
  END IF;
  IF char_length(COALESCE(v_description, '')) > 1000 THEN
    RAISE EXCEPTION 'The description can be at most 1000 characters.' USING ERRCODE = '22023';
  END IF;

  SELECT COALESCE(array_agg(o ORDER BY n), '{}') INTO v_options
  FROM (
    SELECT btrim(x) AS o, n FROM unnest(COALESCE(p_options, '{}'::text[])) WITH ORDINALITY AS u(x, n)
    WHERE NULLIF(btrim(x), '') IS NOT NULL
  ) s;

  IF cardinality(v_options) < 2 OR cardinality(v_options) > 6 THEN
    RAISE EXCEPTION 'Give the poll 2 to 6 options.' USING ERRCODE = '22023';
  END IF;
  IF EXISTS (SELECT 1 FROM unnest(v_options) o WHERE char_length(o) > 120) THEN
    RAISE EXCEPTION 'Each option can be at most 120 characters.' USING ERRCODE = '22023';
  END IF;
  IF (SELECT count(DISTINCT lower(o)) FROM unnest(v_options) o) <> cardinality(v_options) THEN
    RAISE EXCEPTION 'Each option must be different.' USING ERRCODE = '22023';
  END IF;
  IF p_expires_at IS NOT NULL AND p_expires_at <= now() + interval '5 minutes' THEN
    RAISE EXCEPTION 'The closing time must be in the future.' USING ERRCODE = '22023';
  END IF;

  INSERT INTO public.polls (company_id, created_by, question, description, status, expires_at)
  VALUES (v_company, auth.uid(), v_question, v_description, 'active', p_expires_at)
  RETURNING id INTO v_id;

  INSERT INTO public.poll_options (poll_id, company_id, option_text, position)
  SELECT v_id, v_company, o, (n - 1)::int FROM unnest(v_options) WITH ORDINALITY AS u(o, n);

  v_told := public._engagement_notify_employees(
    v_company, NULL, 'poll', 'New poll: ' || left(v_question, 160),
    COALESCE(left(v_description, 140), 'Cast your vote. It takes a second.'), '/portal/polls'
  );
  PERFORM public.log_activity(
    'poll.created', format('Started the poll "%s"', v_question),
    jsonb_build_object('poll_id', v_id, 'options', cardinality(v_options), 'expires_at', p_expires_at, 'notified', v_told)
  );
  RETURN v_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.engagement_set_poll_status(p_id uuid, p_status text)
RETURNS void
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_company uuid := public._engagement_require_hr();
  v_question text;
BEGIN
  IF p_status NOT IN ('active', 'closed') THEN
    RAISE EXCEPTION 'Unknown poll status.' USING ERRCODE = '22023';
  END IF;
  UPDATE public.polls p
  SET status = p_status,
      closed_at = CASE WHEN p_status = 'closed' THEN now() END,
      -- Reopening a poll that ran out of time removes the deadline.
      expires_at = CASE WHEN p_status = 'active' AND p.expires_at <= now() THEN NULL ELSE p.expires_at END
  WHERE p.id = p_id AND p.company_id = v_company
  RETURNING p.question INTO v_question;
  IF v_question IS NULL THEN
    RAISE EXCEPTION 'That poll no longer exists.' USING ERRCODE = 'P0002';
  END IF;
  PERFORM public.log_activity(
    CASE WHEN p_status = 'closed' THEN 'poll.closed' ELSE 'poll.reopened' END,
    format('%s the poll "%s"', CASE WHEN p_status = 'closed' THEN 'Closed' ELSE 'Reopened' END, v_question),
    jsonb_build_object('poll_id', p_id)
  );
END;
$$;

