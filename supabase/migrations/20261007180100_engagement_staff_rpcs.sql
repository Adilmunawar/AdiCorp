CREATE OR REPLACE FUNCTION public.engagement_announcements()
RETURNS json
LANGUAGE plpgsql STABLE SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_company uuid := public._engagement_require_hr();
BEGIN
  RETURN (
    SELECT COALESCE(json_agg(json_build_object(
      'id', a.id, 'title', a.title, 'content', a.content, 'pinned', a.pinned, 'is_active', a.is_active,
      'audience', a.audience, 'department_id', a.department_id, 'department_name', d.name,
      'created_at', a.created_at, 'updated_at', a.updated_at,
      'author_name', public._engagement_staff_name(a.created_by),
      'edited_by_name', CASE WHEN a.updated_by IS NOT NULL THEN public._engagement_staff_name(a.updated_by) END
    ) ORDER BY a.pinned DESC, a.created_at DESC, a.id DESC), '[]'::json)
    FROM public.announcements a
    LEFT JOIN public.departments d ON d.id = a.department_id
    WHERE a.company_id = v_company
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.engagement_save_announcement(
  p_id uuid, p_title text, p_content text, p_pinned boolean DEFAULT false,
  p_audience text DEFAULT 'all', p_department uuid DEFAULT NULL
)
RETURNS uuid
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_company uuid := public._engagement_require_hr();
  v_title text := btrim(COALESCE(p_title, ''));
  v_content text := btrim(COALESCE(p_content, ''));
  v_pinned boolean := COALESCE(p_pinned, false);
  v_audience text := COALESCE(NULLIF(btrim(p_audience), ''), 'all');
  v_dept uuid;
  v_dept_name text;
  v_id uuid;
  v_told integer := 0;
BEGIN
  IF char_length(v_title) < 3 OR char_length(v_title) > 120 THEN
    RAISE EXCEPTION 'The title must be 3 to 120 characters.' USING ERRCODE = '22023';
  END IF;
  IF v_content = '' THEN
    RAISE EXCEPTION 'Write the announcement first.' USING ERRCODE = '22023';
  END IF;
  IF char_length(v_content) > 4000 THEN
    RAISE EXCEPTION 'The announcement can be at most 4000 characters.' USING ERRCODE = '22023';
  END IF;
  IF v_audience NOT IN ('all', 'department') THEN
    RAISE EXCEPTION 'Choose who should see it.' USING ERRCODE = '22023';
  END IF;
  IF v_audience = 'department' THEN
    SELECT d.id, d.name INTO v_dept, v_dept_name
    FROM public.departments d WHERE d.id = p_department AND d.company_id = v_company;
    IF v_dept IS NULL THEN
      RAISE EXCEPTION 'Choose the department that should see it.' USING ERRCODE = '22023';
    END IF;
  END IF;

  IF p_id IS NULL THEN
    INSERT INTO public.announcements (company_id, created_by, title, content, is_active, pinned, audience, department_id)
    VALUES (v_company, auth.uid(), v_title, v_content, true, v_pinned, v_audience, v_dept)
    RETURNING id INTO v_id;

    v_told := public._engagement_notify_employees(
      v_company, v_dept, 'announcement',
      CASE WHEN v_pinned THEN 'Pinned: ' ELSE '' END || v_title,
      left(public._engagement_plain(v_content), 140),
      '/portal/announcements'
    );
    PERFORM public.log_activity(
      'announcement.created',
      format('Posted the announcement "%s"%s', v_title, CASE WHEN v_dept_name IS NOT NULL THEN ' for ' || v_dept_name ELSE '' END),
      jsonb_build_object('announcement_id', v_id, 'pinned', v_pinned, 'audience', v_audience, 'department', v_dept_name, 'notified', v_told)
    );
  ELSE
    UPDATE public.announcements a
    SET title = v_title, content = v_content, pinned = v_pinned, audience = v_audience,
        department_id = v_dept, updated_by = auth.uid()
    WHERE a.id = p_id AND a.company_id = v_company
    RETURNING a.id INTO v_id;
    IF v_id IS NULL THEN
      RAISE EXCEPTION 'That announcement no longer exists.' USING ERRCODE = 'P0002';
    END IF;
    PERFORM public.log_activity(
      'announcement.updated', format('Edited the announcement "%s"', v_title),
      jsonb_build_object('announcement_id', v_id, 'pinned', v_pinned, 'audience', v_audience, 'department', v_dept_name)
    );
  END IF;
  RETURN v_id;
END;
$$;

