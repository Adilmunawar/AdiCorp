-- Company of an HR / owner caller, or an error.
CREATE OR REPLACE FUNCTION public._engagement_require_hr()
RETURNS uuid
LANGUAGE plpgsql STABLE SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_company uuid := public.auth_company_id();
BEGIN
  IF auth.uid() IS NULL OR v_company IS NULL OR NOT public.auth_is_hr() THEN
    RAISE EXCEPTION 'Only HR can do this.' USING ERRCODE = '42501';
  END IF;
  RETURN v_company;
END;
$$;

-- "Today" for engagement dates (birthdays, wishes, greetings).
CREATE OR REPLACE FUNCTION public._engagement_today()
RETURNS date
LANGUAGE sql STABLE
SET search_path = ''
AS $$
  SELECT (now() AT TIME ZONE 'Asia/Karachi')::date
$$;

CREATE OR REPLACE FUNCTION public._engagement_staff_name(p_user uuid)
RETURNS text
LANGUAGE sql STABLE SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT COALESCE(
    (SELECT NULLIF(btrim(concat_ws(' ', p.first_name, p.last_name)), '') FROM public.profiles p WHERE p.id = p_user),
    'HR'
  )
$$;

-- Announcement text without the formatting marks, for notification bodies.
CREATE OR REPLACE FUNCTION public._engagement_plain(p_text text)
RETURNS text
LANGUAGE sql IMMUTABLE
SET search_path = ''
AS $$
  SELECT btrim(regexp_replace(
    regexp_replace(
      regexp_replace(COALESCE(p_text, ''), '\[([^\]]*)\]\([^)]*\)', '\1', 'g'),  -- [label](url) -> label
      '(^|\s)(#{1,3}|-|\d+\.|>)\s', '\1', 'g'),                                 -- headings, bullets, quotes
    '[*_`~]+|\s+', ' ', 'g'))
$$;

-- Realtime broadcast topic of one employee's chat thread (unguessable, carries only message ids).
CREATE OR REPLACE FUNCTION public._engagement_chat_topic(p_employee uuid)
RETURNS text
LANGUAGE sql STABLE SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT 'chat:' || encode(extensions.hmac(p_employee::text, c.chat_secret, 'sha256'), 'hex')
  FROM engagement_private.config c
  WHERE c.id
$$;

-- Tell the employee's open portal tabs that their thread changed. Never fails the caller.
CREATE OR REPLACE FUNCTION public._engagement_ping_thread(p_employee uuid, p_message uuid)
RETURNS void
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  PERFORM realtime.send(jsonb_build_object('id', p_message), 'message', public._engagement_chat_topic(p_employee), false);
EXCEPTION WHEN OTHERS THEN
  NULL;
END;
$$;

-- Fan-out to active employees (all, or one department). Returns how many were told.
CREATE OR REPLACE FUNCTION public._engagement_notify_employees(
  p_company uuid, p_department uuid, p_kind text, p_title text, p_body text, p_href text
)
RETURNS integer
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_count integer;
BEGIN
  INSERT INTO public.notifications (company_id, employee_id, kind, title, body, href)
  SELECT p_company, e.id, p_kind, left(btrim(p_title), 200), NULLIF(left(p_body, 2000), ''), p_href
  FROM public.employees e
  WHERE e.company_id = p_company
    AND e.status = 'active'
    AND (p_department IS NULL OR e.department_id = p_department);
  GET DIAGNOSTICS v_count = ROW_COUNT;
  RETURN v_count;
END;
$$;

-- Occasions of active employees between two dates (inclusive).
-- Birthdays use day and month only; 29 February is celebrated on the 28th in other years.
CREATE OR REPLACE FUNCTION public._engagement_occasions(p_company uuid, p_from date, p_to date)
RETURNS TABLE (
  employee_id uuid, name text, rank text, avatar_url text, department text,
  kind text, years integer, on_date date, shared boolean
)
LANGUAGE sql STABLE SECURITY DEFINER
SET search_path = ''
AS $$
  WITH days AS (
    SELECT d::date AS d
    FROM generate_series(p_from::timestamp, LEAST(p_to, p_from + 366)::timestamp, interval '1 day') AS g(d)
  ),
  people AS (
    SELECT e.id, e.name, e.rank, e.avatar_url, dep.name AS department, e.date_of_birth, e.joining_date, e.share_birthday
    FROM public.employees e
    LEFT JOIN public.departments dep ON dep.id = e.department_id
    WHERE e.company_id = p_company AND e.status = 'active'
  ),
  matches AS (
    SELECT p.*, d.d,
      CASE WHEN to_char(p.date_of_birth, 'MM-DD') = '02-29'
                AND NOT (extract(year FROM d.d)::int % 4 = 0 AND (extract(year FROM d.d)::int % 100 <> 0 OR extract(year FROM d.d)::int % 400 = 0))
           THEN '02-28' ELSE to_char(p.date_of_birth, 'MM-DD') END AS birth_md,
      CASE WHEN to_char(p.joining_date, 'MM-DD') = '02-29'
                AND NOT (extract(year FROM d.d)::int % 4 = 0 AND (extract(year FROM d.d)::int % 100 <> 0 OR extract(year FROM d.d)::int % 400 = 0))
           THEN '02-28' ELSE to_char(p.joining_date, 'MM-DD') END AS join_md
    FROM people p CROSS JOIN days d
  )
  SELECT m.id, m.name, m.rank, m.avatar_url, m.department, 'birthday', 0, m.d, m.share_birthday
  FROM matches m
  WHERE m.date_of_birth IS NOT NULL AND m.birth_md = to_char(m.d, 'MM-DD')
  UNION ALL
  SELECT m.id, m.name, m.rank, m.avatar_url, m.department, 'anniversary',
         (extract(year FROM m.d) - extract(year FROM m.joining_date))::int, m.d, true
  FROM matches m
  WHERE m.joining_date IS NOT NULL AND m.joining_date < m.d AND m.join_md = to_char(m.d, 'MM-DD')
    AND extract(year FROM m.d) > extract(year FROM m.joining_date)
  UNION ALL
  SELECT m.id, m.name, m.rank, m.avatar_url, m.department, 'welcome', 0, m.d, true
  FROM matches m
  WHERE m.joining_date = m.d
$$;

