CREATE OR REPLACE FUNCTION public.tg_notifications_push()
RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_url text;
  v_secret text;
  v_key text;
  v_headers jsonb;
BEGIN
  IF NEW.user_id IS NOT NULL THEN
    IF NOT EXISTS (SELECT 1 FROM public.push_subscriptions s WHERE s.user_id = NEW.user_id) THEN
      RETURN NULL;
    END IF;
  ELSIF NEW.employee_id IS NOT NULL THEN
    IF NOT EXISTS (SELECT 1 FROM public.push_subscriptions s WHERE s.employee_id = NEW.employee_id) THEN
      RETURN NULL;
    END IF;
  ELSE
    RETURN NULL;
  END IF;

  SELECT c.function_url, c.webhook_secret, c.function_key INTO v_url, v_secret, v_key
  FROM engagement_private.config c WHERE c.id;
  IF v_url IS NULL OR v_secret IS NULL THEN
    RETURN NULL;
  END IF;

  v_headers := jsonb_build_object('Content-Type', 'application/json', 'x-push-secret', v_secret);
  IF v_key IS NOT NULL THEN
    v_headers := v_headers || jsonb_build_object('Authorization', 'Bearer ' || v_key, 'apikey', v_key);
  END IF;

  PERFORM net.http_post(
    url := v_url,
    body := jsonb_build_object('notification_id', NEW.id),
    headers := v_headers,
    timeout_milliseconds := 10000
  );
  RETURN NULL;
EXCEPTION WHEN OTHERS THEN
  -- Push is best effort: the in-app notification is always kept.
  RETURN NULL;
END;
$$;
REVOKE ALL ON FUNCTION public.tg_notifications_push() FROM PUBLIC, anon, authenticated;

DROP TRIGGER IF EXISTS notifications_push ON public.notifications;
CREATE TRIGGER notifications_push
  AFTER INSERT ON public.notifications
  FOR EACH ROW EXECUTE FUNCTION public.tg_notifications_push();

