-- base64url -> bytes, or NULL when it is not valid base64url.
CREATE OR REPLACE FUNCTION public._push_b64u(p text)
RETURNS bytea
LANGUAGE plpgsql IMMUTABLE
SET search_path = ''
AS $$
DECLARE
  v text := translate(rtrim(COALESCE(p, ''), '='), '-_', '+/');
BEGIN
  IF v = '' OR v !~ '^[A-Za-z0-9+/]+$' THEN
    RETURN NULL;
  END IF;
  RETURN decode(v || repeat('=', (4 - length(v) % 4) % 4), 'base64');
EXCEPTION WHEN OTHERS THEN
  RETURN NULL;
END;
$$;
REVOKE ALL ON FUNCTION public._push_b64u(text) FROM PUBLIC, anon, authenticated;

-- Saves a browser's subscription for one recipient (exactly one of p_user / p_employee).
-- Only the real push services are accepted, so the server never posts anywhere else.
CREATE OR REPLACE FUNCTION public._push_save(
  p_company uuid, p_user uuid, p_employee uuid, p_subscription jsonb, p_device text
)
RETURNS json
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_endpoint text := p_subscription ->> 'endpoint';
  v_p256dh text := p_subscription #>> '{keys,p256dh}';
  v_auth text := p_subscription #>> '{keys,auth}';
  v_pub bytea := public._push_b64u(v_p256dh);
  v_sec bytea := public._push_b64u(v_auth);
  v_device text := left(COALESCE(NULLIF(btrim(p_device), ''), 'Browser'), 80);
  v_before public.push_subscriptions;
  v_created boolean;
  v_devices integer;
BEGIN
  IF v_endpoint IS NULL OR char_length(v_endpoint) < 20 OR char_length(v_endpoint) > 2048 THEN
    RETURN json_build_object('error', 'The notification address is missing or too long.');
  END IF;
  IF v_endpoint !~ '^https://(fcm\.googleapis\.com|android\.googleapis\.com|([a-z0-9-]+\.)*push\.services\.mozilla\.com|([a-z0-9-]+\.)*notify\.windows\.com|([a-z0-9-]+\.)*push\.apple\.com)/' THEN
    RETURN json_build_object('error', 'This browser''s notification service is not supported. Use Chrome, Edge, Firefox or Safari.');
  END IF;
  IF v_pub IS NULL OR length(v_pub) <> 65 OR get_byte(v_pub, 0) <> 4 OR v_sec IS NULL OR length(v_sec) <> 16 THEN
    RETURN json_build_object('error', 'The browser''s notification keys are missing or invalid.');
  END IF;

  SELECT * INTO v_before FROM public.push_subscriptions s WHERE s.endpoint = v_endpoint;
  v_created := v_before.id IS NULL
    OR v_before.user_id IS DISTINCT FROM p_user
    OR v_before.employee_id IS DISTINCT FROM p_employee;

  -- The same browser used by someone else now notifies them instead.
  INSERT INTO public.push_subscriptions (company_id, user_id, employee_id, endpoint, p256dh, auth, device)
  VALUES (p_company, p_user, p_employee, v_endpoint, v_p256dh, v_auth, v_device)
  ON CONFLICT (endpoint) DO UPDATE SET
    company_id = EXCLUDED.company_id,
    user_id = EXCLUDED.user_id,
    employee_id = EXCLUDED.employee_id,
    p256dh = EXCLUDED.p256dh,
    auth = EXCLUDED.auth,
    device = EXCLUDED.device,
    created_at = CASE WHEN v_created THEN now() ELSE public.push_subscriptions.created_at END,
    failures = 0,
    last_error = NULL;

  -- At most 8 devices per person; the least recently working go first.
  DELETE FROM public.push_subscriptions s
  WHERE s.id IN (
    SELECT x.id FROM public.push_subscriptions x
    WHERE (p_user IS NOT NULL AND x.user_id = p_user) OR (p_employee IS NOT NULL AND x.employee_id = p_employee)
    ORDER BY COALESCE(x.last_ok_at, x.created_at) DESC, x.id DESC
    OFFSET 8
  );

  SELECT count(*)::int INTO v_devices FROM public.push_subscriptions x
  WHERE (p_user IS NOT NULL AND x.user_id = p_user) OR (p_employee IS NOT NULL AND x.employee_id = p_employee);

  RETURN json_build_object('ok', true, 'created', v_created, 'devices', v_devices);
END;
$$;
REVOKE ALL ON FUNCTION public._push_save(uuid, uuid, uuid, jsonb, text) FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public._push_devices_json(p_user uuid, p_employee uuid)
RETURNS json
LANGUAGE sql STABLE SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT COALESCE(json_agg(json_build_object(
    'id', s.id, 'device', s.device, 'created_at', s.created_at, 'last_ok_at', s.last_ok_at,
    'last_error', s.last_error, 'failures', s.failures,
    'endpoint_hash', encode(extensions.digest(s.endpoint, 'sha256'), 'hex')
  ) ORDER BY COALESCE(s.last_ok_at, s.created_at) DESC), '[]'::json)
  FROM public.push_subscriptions s
  WHERE (p_user IS NOT NULL AND s.user_id = p_user) OR (p_employee IS NOT NULL AND s.employee_id = p_employee)
$$;
REVOKE ALL ON FUNCTION public._push_devices_json(uuid, uuid) FROM PUBLIC, anon, authenticated;

-- ---------------------------------------------------------------------------
-- Staff RPCs (any staff role: owner, HR, Finance all get notifications)
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.push_subscribe(p_subscription jsonb, p_device text DEFAULT NULL, p_welcome boolean DEFAULT true)
RETURNS json
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_company uuid := public.auth_company_id();
  v_result json;
BEGIN
  IF auth.uid() IS NULL OR v_company IS NULL OR NOT public.auth_is_staff() THEN
    RAISE EXCEPTION 'not allowed' USING ERRCODE = '42501';
  END IF;
  v_result := public._push_save(v_company, auth.uid(), NULL, p_subscription, p_device);
  IF COALESCE((v_result ->> 'created')::boolean, false) AND COALESCE(p_welcome, true) THEN
    PERFORM public.notify_user(v_company, auth.uid(), 'push.welcome', 'Notifications are on for this device',
      'Approvals, messages and announcements will reach you here, even when AdiCorp is closed.', '/notifications');
  END IF;
  RETURN v_result;
END;
$$;

CREATE OR REPLACE FUNCTION public.push_unsubscribe(p_endpoint text)
RETURNS json
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_count integer;
BEGIN
  IF auth.uid() IS NULL THEN
    RAISE EXCEPTION 'not allowed' USING ERRCODE = '42501';
  END IF;
  DELETE FROM public.push_subscriptions s WHERE s.user_id = auth.uid() AND s.endpoint = p_endpoint;
  GET DIAGNOSTICS v_count = ROW_COUNT;
  RETURN json_build_object('ok', true, 'removed', v_count);
END;
$$;

