-- Engagement 4/4: web push. Every notifications row is pushed to the recipient's devices.
--   * Browsers subscribe through push_subscribe (staff) / portal_push_subscribe (portal).
--   * AFTER INSERT on notifications queues an async HTTP call (pg_net) to the 'push-send'
--     Edge Function with only the notification id and a shared secret (plus the anon JWT for
--     the verify_jwt gateway).
--   * push-send reads the row and the VAPID key pair with the service role, encrypts
--     (RFC 8291 aes128gcm) and posts to each device, pruning dead subscriptions.
--   * The VAPID private key lives only in engagement_private.config (service role via
--     _push_config); it is generated by push-send on first use.
--   * pg_cron sends the 09:00 celebration greetings.

DO $$
BEGIN
  CREATE EXTENSION IF NOT EXISTS pg_net WITH SCHEMA extensions;
EXCEPTION WHEN OTHERS THEN
  RAISE NOTICE 'pg_net is not available (%); push delivery stays off until it is enabled.', SQLERRM;
END $$;

