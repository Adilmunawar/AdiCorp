-- Stores the key pair once; concurrent first calls converge on the stored pair.
CREATE OR REPLACE FUNCTION public._push_store_vapid(p_public text, p_private jsonb)
RETURNS text
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_public text;
BEGIN
  IF p_public !~ '^[A-Za-z0-9_-]{80,100}$' OR p_private ->> 'd' IS NULL THEN
    RAISE EXCEPTION 'Invalid VAPID key pair' USING ERRCODE = '22023';
  END IF;
  UPDATE engagement_private.config c
  SET vapid_public = p_public, vapid_private = p_private, updated_at = now()
  WHERE c.id AND c.vapid_public IS NULL;
  SELECT c.vapid_public INTO v_public FROM engagement_private.config c WHERE c.id;
  RETURN v_public;
END;
$$;
REVOKE ALL ON FUNCTION public._push_store_vapid(text, jsonb) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public._push_store_vapid(text, jsonb) TO service_role;

